"""Executive-grade Blameless RCA Postmortem PDF Generator.

Produces professional, audit-compliant Root Cause Analysis reports
utilizing ReportLab with modern typography, colored status callouts,
timeline blocks, and preventative action tables.
"""

from __future__ import annotations

import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from rca_agent.models.schema import BlamelessRCA


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for dynamic 'Page X of Y' numbering and header/footer rules."""

    def __init__(self, *args, **kwargs) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int) -> None:
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 755, "Blameless Root Cause Analysis (RCA) — Confidential")
            self.drawRightString(letter[0] - 54, 755, "Generated by rca-agent")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, 748, letter[0] - 54, 748)

        # Running Footer
        page_str = f"Page {self._pageNumber} of {total_pages}"
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 45, letter[0] - 54, 45)

        self.drawString(54, 32, "STRICTLY BLAMELESS POSTMORTEM — FOCUSED ON SYSTEMS & GUARDRAILS")
        self.drawRightString(letter[0] - 54, 32, page_str)
        self.restoreState()


def generate_rca_pdf(
    rca: BlamelessRCA,
    output_path: str | Path,
    commit_hash: str,
    repo_name: str | None = None,
    model_name: str = "Google Gemini 2.5 Flash",
) -> Path:
    """Generate a high-quality PDF report from a BlamelessRCA instance.

    Parameters
    ----------
    rca:
        The validated BlamelessRCA postmortem model.
    output_path:
        Target file path for the generated PDF.
    commit_hash:
        SHA of the investigated commit.
    repo_name:
        Optional name or path of the repository.
    model_name:
        Name of the reasoning LLM model used in the investigation.

    Returns
    -------
    Path
        Absolute path to the created PDF file.
    """
    dest = Path(output_path).expanduser().resolve()
    dest.parent.mkdir(parents=True, exist_ok=True)

    doc = SimpleDocTemplate(
        str(dest),
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Color Palette Definitions
    c_primary = colors.HexColor("#0F172A")  # Slate 900
    c_blue = colors.HexColor("#2563EB")  # Blue 600
    c_blue_bg = colors.HexColor("#EFF6FF")  # Blue 50
    c_red = colors.HexColor("#DC2626")  # Red 600
    c_red_bg = colors.HexColor("#FEF2F2")  # Red 50
    c_green = colors.HexColor("#16A34A")  # Green 600
    c_green_bg = colors.HexColor("#F0FDF4")  # Green 50
    c_slate_bg = colors.HexColor("#F8FAFC")  # Slate 50
    c_border = colors.HexColor("#CBD5E1")  # Slate 300
    c_muted = colors.HexColor("#64748B")  # Slate 500

    # Custom Typography Styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=c_primary,
    )

    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=c_muted,
    )

    h2_style = ParagraphStyle(
        "SectionH2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=17,
        textColor=c_primary,
        spaceBefore=12,
        spaceAfter=6,
    )

    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=14,
        textColor=c_primary,
    )

    body_bold = ParagraphStyle(
        "BodyBold",
        parent=body_style,
        fontName="Helvetica-Bold",
    )

    content_width = letter[0] - 108  # 504 pt width

    story = []

    # 1. Header Banner
    header_table_data = [
        [
            Paragraph(
                "<b>ROOT CAUSE ANALYSIS</b><br/><font size=8 color='#64748B'>BLAMELESS SRE POSTMORTEM REPORT</font>",
                title_style,
            ),
            Paragraph(
                "<font size=8 color='#16A34A'><b>● STATUS: RESOLVED</b></font><br/>"
                f"<font size=8 color='#64748B'>Date: {datetime.datetime.now(datetime.UTC).strftime('%Y-%m-%d %H:%M UTC')}</font>",
                ParagraphStyle("HeaderMeta", parent=subtitle_style, alignment=2),
            ),
        ]
    ]
    header_table = Table(header_table_data, colWidths=[330, 174])
    header_table.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
                ("TOPPADDING", (0, 0), (-1, -1), 0),
            ]
        )
    )
    story.append(header_table)
    story.append(Spacer(1, 10))
    story.append(
        HRFlowable(width="100%", thickness=1.5, color=c_blue, spaceBefore=4, spaceAfter=12)
    )

    # 2. Metadata Key-Value Box
    meta_rows = [
        [
            Paragraph("<b>Target Commit:</b>", body_style),
            Paragraph(
                f"<font color='#2563EB'><b>{commit_hash[:12]}</b> ({commit_hash})</font>",
                body_style,
            ),
            Paragraph("<b>Reasoning Engine:</b>", body_style),
            Paragraph(f"{model_name}", body_style),
        ],
        [
            Paragraph("<b>Repository:</b>", body_style),
            Paragraph(f"{repo_name or 'Local Repository'}", body_style),
            Paragraph("<b>Investigation Protocol:</b>", body_style),
            Paragraph("5 Whys Framework (Agno)", body_style),
        ],
    ]
    meta_table = Table(meta_rows, colWidths=[90, 162, 110, 142])
    meta_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), c_slate_bg),
                ("BOX", (0, 0), (-1, -1), 0.5, c_border),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ]
        )
    )
    story.append(meta_table)
    story.append(Spacer(1, 14))

    # 3. Executive Summary (Blue Callout Box)
    story.append(Paragraph("📋 Executive Summary", h2_style))
    summary_p = Paragraph(rca.executive_summary, body_style)
    summary_box = Table([[summary_p]], colWidths=[content_width])
    summary_box.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), c_blue_bg),
                ("BOX", (0, 0), (-1, -1), 1, c_blue),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("LEFTPADDING", (0, 0), (-1, -1), 12),
                ("RIGHTPADDING", (0, 0), (-1, -1), 12),
            ]
        )
    )
    story.append(summary_box)
    story.append(Spacer(1, 12))

    # 4. Incident Timeline (Structural Decay)
    story.append(Paragraph("⏱️ Incident Timeline (Structural Decay)", h2_style))
    timeline_data = []
    for i, event in enumerate(rca.incident_timeline, 1):
        step_badge = Paragraph(f"<font color='#2563EB'><b>T+{i:02d}</b></font>", body_bold)
        event_p = Paragraph(event, body_style)
        timeline_data.append([step_badge, event_p])

    timeline_table = Table(timeline_data, colWidths=[50, content_width - 50])
    timeline_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.white),
                ("LINEBELOW", (0, 0), (-1, -1), 0.5, colors.HexColor("#F1F5F9")),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )
    story.append(timeline_table)
    story.append(Spacer(1, 12))

    # 5. Root Cause Analysis (5 Whys Framework)
    story.append(Paragraph("🎯 Root Cause Analysis (5 Whys Framework)", h2_style))
    formatted_rca = rca.root_cause_analysis.replace("\n", "<br/>")
    rca_p = Paragraph(formatted_rca, body_style)
    rca_box = Table([[rca_p]], colWidths=[content_width])
    rca_box.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), c_slate_bg),
                ("BOX", (0, 0), (-1, -1), 0.5, c_border),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("LEFTPADDING", (0, 0), (-1, -1), 12),
                ("RIGHTPADDING", (0, 0), (-1, -1), 12),
            ]
        )
    )
    story.append(rca_box)
    story.append(Spacer(1, 12))

    # 6. Blast Radius & Downstream Impact (Red Callout Box)
    story.append(
        KeepTogether(
            [
                Paragraph("💥 Blast Radius & Downstream Impact", h2_style),
                Table(
                    [
                        [
                            Paragraph(
                                f"<font color='#DC2626'><b>⚠️ IMPACT:</b></font> {item}", body_style
                            )
                        ]
                        for item in rca.blast_radius
                    ],
                    colWidths=[content_width],
                    style=[
                        ("BACKGROUND", (0, 0), (-1, -1), c_red_bg),
                        ("BOX", (0, 0), (-1, -1), 1, c_red),
                        ("TOPPADDING", (0, 0), (-1, -1), 6),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                        ("LEFTPADDING", (0, 0), (-1, -1), 10),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                        ("LINEBELOW", (0, 0), (-1, -2), 0.5, colors.HexColor("#FCA5A5")),
                    ],
                ),
                Spacer(1, 12),
            ]
        )
    )

    # 7. Preventative Guardrails & Action Items (Green Box)
    story.append(
        KeepTogether(
            [
                Paragraph("🛡️ Preventative Guardrails & Action Items", h2_style),
                Table(
                    [
                        [
                            Paragraph(f"<font color='#16A34A'><b>[{i}]</b></font>", body_bold),
                            Paragraph(action, body_style),
                        ]
                        for i, action in enumerate(rca.preventative_action_items, 1)
                    ],
                    colWidths=[35, content_width - 35],
                    style=[
                        ("BACKGROUND", (0, 0), (-1, -1), c_green_bg),
                        ("BOX", (0, 0), (-1, -1), 1, c_green),
                        ("TOPPADDING", (0, 0), (-1, -1), 6),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                        ("LEFTPADDING", (0, 0), (-1, -1), 8),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                        ("LINEBELOW", (0, 0), (-1, -2), 0.5, colors.HexColor("#86EFAC")),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ],
                ),
                Spacer(1, 14),
            ]
        )
    )

    # Build the document with two-pass canvas
    doc.build(story, canvasmaker=NumberedCanvas)
    return dest
