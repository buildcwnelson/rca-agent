"""Slack and GitHub PR incident notification dispatchers.

Formats executive incident briefings for team collaboration channels (Slack)
and automated CI/CD pull request comments (GitHub).
"""

from __future__ import annotations

import json
from urllib import request

from rca_agent.models.schema import BlamelessRCA


def format_github_pr_markdown(
    rca: BlamelessRCA,
    commit_hash: str,
    repo_name: str | None = None,
) -> str:
    """Format a BlamelessRCA report as GitHub-Flavored Markdown for PR comments."""
    short_sha = commit_hash[:8]
    timeline_rows = "\n".join(
        [f"| **T+{i:02d}** | {event} |" for i, event in enumerate(rca.incident_timeline, 1)]
    )

    blast_items = "\n".join([f"- ⚠️ **Impact:** {item}" for item in rca.blast_radius])
    actions = "\n".join(
        [f"- [ ] **[{i}]** {item}" for i, item in enumerate(rca.preventative_action_items, 1)]
    )

    md = f"""## 🔍 Blameless Root Cause Analysis (RCA) Postmortem

> **Repository:** `{repo_name or 'Repository'}` &nbsp;|&nbsp; **Commit:** [`{short_sha}`]({commit_hash}) &nbsp;|&nbsp; **Status:** Resolved

### 📋 Executive Summary
{rca.executive_summary}

<details>
<summary><b>⏱️ Incident Timeline (Structural Decay)</b></summary>

| Step | Milestone |
|:---:|:---|
{timeline_rows}

</details>

### 🎯 Root Cause Analysis (5 Whys Framework)
{rca.root_cause_analysis}

### 💥 Blast Radius & Downstream Impact
{blast_items}

### 🛡️ Preventative Guardrails & Action Items
{actions}

---
*Report autonomously generated by [rca-agent](https://github.com/buildcwnelson/rca-agent).*
"""
    return md


def send_slack_notification(
    webhook_url: str,
    rca: BlamelessRCA,
    commit_hash: str,
    repo_name: str | None = None,
) -> bool:
    """Send an incident briefing card to a Slack incoming webhook.

    Returns True if successfully received by Slack (HTTP 200).
    """
    short_sha = commit_hash[:8]

    # Format Slack Blocks
    payload = {
        "text": f"🚨 Blameless RCA: Incident Postmortem for commit {short_sha}",
        "blocks": [
            {
                "type": "header",
                "text": {
                    "type": "plain_text",
                    "text": f"🔍 Blameless RCA Postmortem — {short_sha}",
                    "emoji": True,
                },
            },
            {
                "type": "section",
                "fields": [
                    {"type": "mrkdwn", "text": f"*Repository:*\n{repo_name or 'Local Repo'}"},
                    {"type": "mrkdwn", "text": f"*Commit:*\n`{short_sha}`"},
                ],
            },
            {
                "type": "section",
                "text": {
                    "type": "mrkdwn",
                    "text": f"*Executive Summary:*\n{rca.executive_summary}",
                },
            },
            {"type": "divider"},
            {
                "type": "section",
                "text": {
                    "type": "mrkdwn",
                    "text": "*💥 Blast Radius:*\n"
                    + "\n".join([f"• ⚠️ {item}" for item in rca.blast_radius[:3]]),
                },
            },
            {
                "type": "section",
                "text": {
                    "type": "mrkdwn",
                    "text": "*🛡️ Top Preventative Guardrails:*\n"
                    + "\n".join([f"• [{i}] {item}" for i, item in enumerate(rca.preventative_action_items[:3], 1)]),
                },
            },
            {
                "type": "context",
                "elements": [
                    {
                        "type": "mrkdwn",
                        "text": "Generated autonomously by *rca-agent* | Strict Blameless Postmortem",
                    }
                ],
            },
        ],
    }

    req = request.Request(
        webhook_url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
    )

    try:
        with request.urlopen(req, timeout=10) as resp:
            return resp.status == 200
    except Exception:
        return False
